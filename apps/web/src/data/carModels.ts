/**
 * 车型库：品牌 → 车系 → 年款区间级联数据源。
 * 参考公开车型信息（汽车之家/懂车帝车型库风格）整理的演示数据集，
 * 覆盖国内主流在售品牌 60+ 家、400+ 车系；正式版可无缝切换为主数据服务 API（接口形状一致）。
 */

export type Fuel = '汽油' | '柴油' | '纯电' | '混动'

export interface CarModelEntry {
  /** 车系名 */
  name: string
  /** 年款区间 [起始年, 结束年]（结束年含当前年在售；停售车系标注实际结束年） */
  years: [number, number]
  /** 燃料类型建议（选中车系自动带出，可改） */
  fuel?: Fuel
}

export interface BrandEntry {
  brand: string
  models: CarModelEntry[]
}

const Y = new Date().getFullYear()

/** 燃油/常规动力车系（默认在售至今） */
const m = (name: string, start: number, end: number = Y): CarModelEntry => ({ name, years: [start, end] })
/** 纯电车系 */
const ev = (name: string, start: number, end: number = Y): CarModelEntry => ({ name, years: [start, end], fuel: '纯电' })
/** 混动/插混/增程车系 */
const hv = (name: string, start: number, end: number = Y): CarModelEntry => ({ name, years: [start, end], fuel: '混动' })

